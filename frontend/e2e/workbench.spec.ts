test('real interactive Shell, refresh reconnect, Chinese annotations and log download', async ({ page }) => {
  await page.getByLabel('搜索全部参数').fill('--shell')
  const shell = page.locator('.tool-card').filter({ has: page.getByText('交互 sqlmap Shell', { exact: true }) })
  await shell.getByRole('button', { name: '运行', exact: true }).click()
  await expect(page.locator('.ready-status')).toHaveText('运行中')
  await expect(page.locator('.note')).toContainText(['sqlmap Shell'], { timeout: 20000 })
  const beforeHeight = (await page.locator('.execution-area').boundingBox())!.height
  await page.locator('.resize-handle').focus()
  await page.keyboard.press('ArrowUp')
  expect((await page.locator('.execution-area').boundingBox())!.height).toBeGreaterThan(beforeHeight)
  await page.locator('.xterm-helper-textarea').focus()
  await page.keyboard.type('help')
  await page.keyboard.press('Enter')
  await expect.poll(async () => {
    const response = await page.request.get('/api/download?root=run&path=terminal.log')
    return response.text()
  }).toContain('valid example')
  await page.reload()
  await expect(page.getByText('终端已连接', { exact: true })).toBeVisible()
  await expect(page.locator('.ready-status')).toHaveText('运行中')
  await page.locator('.xterm-helper-textarea').focus()
  await page.keyboard.type('exit')
  await page.keyboard.press('Enter')
  await expect(page.locator('.ready-status')).toHaveText('已完成', { timeout: 20000 })
  await page.getByRole('tab', { name: /结果文件/ }).click()
  await expect(page.getByText('terminal.log', { exact: true })).toBeVisible()
  const log = await page.request.get('/api/download?root=run&path=terminal.log')
  const transcript = await log.text()
  expect(transcript).toContain('sqlmap >')
  expect(transcript).not.toContain('invalid option(s)')
  expect(transcript).not.toContain('^[[?1;2c')
})

