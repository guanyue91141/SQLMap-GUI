import { test, expect } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test.describe.configure({ mode: 'serial' })
test.beforeEach(async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('244 参数', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '重置', exact: true }).click()
})

test('all categories, Chinese fields, command conflicts and configuration export', async ({ page }) => {
  const pageErrors: string[] = []
  page.on('pageerror', error => pageErrors.push(error.message))
  await expect(page.locator('.group-nav button')).toHaveCount(17)
  await page.getByLabel('目标 URL', { exact: true }).fill('http://127.0.0.1:8000/item?id=1&name=中文')
  await expect(page.locator('.command-preview > code')).toContainText('name=中文')
  await page.getByLabel('搜索全部参数').fill('--risk')
  await page.getByLabel('测试风险', { exact: true }).fill('3')
  await expect(page.locator('.command-preview > code')).toContainText("'--risk' '3'")
  await page.locator('.advanced-section summary').click()
  await page.getByLabel('在分类表单之外补充参数').fill('--risk=2')
  await expect(page.locator('.command-preview > code')).toContainText('参数冲突')
  await expect(page.getByRole('button', { name: '开始运行', exact: true })).toBeDisabled()
  await page.getByLabel('在分类表单之外补充参数').fill('')
  await page.locator('.config-menu summary').click()
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出 JSON 配置' }).click()
  const downloaded = await downloadEvent
  const config = JSON.parse(await readFile((await downloaded.path())!, 'utf-8'))
  expect(config.values.risk).toBe('3')
  expect(config.values.url).toContain('name=中文')
  expect(pageErrors).toEqual([])
})

